#!/usr/bin/env python3
"""
Copy templates/*.md and docs/lab.yaml into the JavaScript library (docs/app/lib/builtin_*.js).

The browser version of the notebook (docs/app/) uses the templates and the lab.yaml in the notebook folder
when they are there and falls back to these built-in copies when they are not (for example a folder that
holds only the record). Run this after editing a template or docs/lab.yaml; tests/test_js_parity.py fails
if a copy is stale.

    python3 scripts/build_js_templates.py           # rewrite the file
    python3 scripts/build_js_templates.py --check   # exit 1 if it is stale
"""
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LIB = REPO_ROOT / "docs" / "app" / "lib"
HEAD = "/* Generated by scripts/build_js_templates.py. Do not edit by hand. */"


def build_templates() -> str:
    lines = [HEAD, "", "export const TEMPLATES = {"]
    # sorted by name as text: sorting Path objects is case-insensitive on Windows and would reorder the file
    for path in sorted((REPO_ROOT / "templates").glob("*.md"), key=lambda p: p.name):
        text = path.read_text(encoding="utf-8")
        lines.append(f"  {json.dumps(path.stem)}: {json.dumps(text, ensure_ascii=False)},")
    lines += ["};", ""]
    return "\n".join(lines)


def build_lab() -> str:
    text = (REPO_ROOT / "docs" / "lab.yaml").read_text(encoding="utf-8")
    return f"{HEAD}\n\nexport const LAB_YAML = {json.dumps(text, ensure_ascii=False)};\n"


OUTPUTS = {LIB / "builtin_templates.js": build_templates, LIB / "builtin_lab.js": build_lab}


def main() -> int:
    stale = 0
    for out, build in OUTPUTS.items():
        new = build()
        if "--check" in sys.argv:
            old = out.read_text(encoding="utf-8") if out.exists() else ""
            if old != new:
                print(f"{out.relative_to(REPO_ROOT).as_posix()} is stale: run python3 scripts/build_js_templates.py")
                stale = 1
            continue
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
        print(f"Wrote {out.relative_to(REPO_ROOT).as_posix()}")
    return stale


if __name__ == "__main__":
    sys.exit(main())
