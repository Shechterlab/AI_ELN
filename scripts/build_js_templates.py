#!/usr/bin/env python3
"""
Copy templates/*.md into docs/app/lib/builtin_templates.js.

The browser version of the notebook (docs/app/) uses the templates in the notebook folder when they are
there and falls back to this built-in copy when they are not (for example a folder that holds only the
record). Run this after editing a template; tests/test_js_parity.py fails if the copy is stale.

    python3 scripts/build_js_templates.py           # rewrite the file
    python3 scripts/build_js_templates.py --check   # exit 1 if it is stale
"""
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "docs" / "app" / "lib" / "builtin_templates.js"


def build() -> str:
    lines = ["/* Generated by scripts/build_js_templates.py from templates/*.md. Do not edit by hand. */", "",
             "export const TEMPLATES = {"]
    # sorted by name as text: sorting Path objects is case-insensitive on Windows and would reorder the file
    for path in sorted((REPO_ROOT / "templates").glob("*.md"), key=lambda p: p.name):
        text = path.read_text(encoding="utf-8")
        lines.append(f"  {json.dumps(path.stem)}: {json.dumps(text, ensure_ascii=False)},")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    new = build()
    if "--check" in sys.argv:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != new:
            print(f"{OUT.relative_to(REPO_ROOT)} is stale: run python3 scripts/build_js_templates.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print(f"Wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
